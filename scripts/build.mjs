// Packs index.html, the stylesheet and all billing modules into one
// self-contained file that opens by double-click (file://), where browsers
// refuse to load ES modules. No dependencies: each module is wrapped in a
// function and its imports/exports are rewritten to a small registry.
//
//   node scripts/build.mjs          -> writes apka-hisab-billing.html
//   node scripts/build.mjs --check  -> fails if that file is out of date

import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(new URL('..', import.meta.url).pathname);
const JS_DIR = 'assets/js/billing/';
const OUTPUT = 'apka-hisab-billing.html';

async function bundleModule(name, seen, order) {
  if (seen.has(name)) return;
  seen.add(name);
  let src = await readFile(resolve(root, JS_DIR, name), 'utf8');
  const exports = [];

  src = src.replace(/import\s*\{([^}]*)\}\s*from\s*'\.\/([\w-]+\.js)';/g, (_, names, dep) => {
    order.deps.push([name, dep]);
    const binding = names.split(',').map((n) => n.trim()).filter(Boolean)
      .map((n) => n.replace(/\s+as\s+/, ': ')).join(', ');
    return `const { ${binding} } = __modules['${dep}'];`;
  });
  src = src.replace(/^export\s+(async\s+function|function|class|const|let)\s+([\w$]+)/gm, (_, kind, id) => {
    exports.push(id);
    return `${kind} ${id}`;
  });
  if (/^\s*(import|export)\s/m.test(src)) throw new Error(`${name}: unsupported import/export syntax`);

  for (const [from, dep] of order.deps.filter(([f]) => f === name)) await bundleModule(dep, seen, order);
  order.list.push({ name, code: `__modules['${name}'] = (function () {\n${src}\nreturn { ${exports.join(', ')} };\n})();` });
}

export async function build() {
  const html = await readFile(resolve(root, 'index.html'), 'utf8');
  const css = await readFile(resolve(root, 'assets/css/billing.css'), 'utf8');
  const order = { list: [], deps: [] };
  await bundleModule('app.js', new Set(), order);
  const js = `(function () {\n'use strict';\nconst __modules = {};\n${order.list.map((m) => m.code).join('\n\n')}\n})();`;
  if (js.includes('</script')) throw new Error('bundle contains </script');

  const linkTag = '<link rel="stylesheet" href="assets/css/billing.css">';
  const scriptTag = '<script type="module" src="assets/js/billing/app.js"></script>';
  if (!html.includes(linkTag) || !html.includes(scriptTag)) throw new Error('index.html tags not found');
  // The single file has no manifest, icons or service worker next to it.
  const page = html.replace(/^\s*<(link rel="(manifest|icon|apple-touch-icon)"|meta name="(apple-mobile-web-app-capable|mobile-web-app-capable)")[^>]*>\n/gm, '');
  return '<!-- Generated by scripts/build.mjs from index.html and assets/. Do not edit by hand. -->\n'
    + page.replace(linkTag, () => `<style>\n${css}</style>`).replace(scriptTag, () => `<script>\n${js}\n</script>`);
}

const out = await build();
const target = resolve(root, OUTPUT);
if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current !== out) { console.error(`${OUTPUT} is out of date. Run: npm run build`); process.exit(1); }
  console.log(`${OUTPUT} is up to date.`);
} else {
  await writeFile(target, out);
  console.log(`Wrote ${OUTPUT} (${Math.round(out.length / 1024)} KB)`);
}
